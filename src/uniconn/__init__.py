def __getattr__(name: str) -> Any:
    """Ленивый доступ к устаревшим реэкспортам (не включённым в ``__all__``)."""
    if name == "quote":
        from shlex import quote

        return quote
    msg = f"module {__name__!r} has no attribute {name!r}"
    raise AttributeError(msg)


